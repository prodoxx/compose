"""Local OpenAI-compatible providers from config.json's `providers` map, for the harnesses: pi's extension file and env,
the reach check and doctor rows, OpenCode's provider, and the price of a turn."""
from __future__ import annotations  # the X | None annotations on /usr/bin/python3 3.9
import json
import os
import fc_config
import fc_core

PI_JS = """// generated by compose from ~/.compose/config.json providers; do not edit
const PROVIDERS = <json>;
export default function (pi) {
  const want = process.env.COMPOSE_PI_MODEL || "";
  for (const p of PROVIDERS) {
    const ids = p.models.length ? p.models : want.startsWith(p.name + "/") ? [want.slice(p.name.length + 1)] : [];
    pi.registerProvider(p.name, { name: p.name, baseUrl: p.baseUrl, apiKey: p.apiKeyEnv ? process.env[p.apiKeyEnv] || "" : "none", api: "openai-completions",
      models: ids.map((id) => ({ id, name: id, reasoning: false, input: ["text"], cost: { input: 0, output: 0, cacheRead: 0, cacheWrite: 0 }, contextWindow: 131072, maxTokens: 16384 })) });
  }
}
"""


def pi_extension_text() -> str:
    """The text of ~/.compose/pi-providers.js, rendered from fc_config.PROVIDERS."""
    envs = {n: fc_config.provider_env(n) for n in fc_config.PROVIDERS}
    rows = [{"apiKeyEnv": envs[n] if envs[n] in os.environ else None, "baseUrl": p["base_url"], "models": p.get("models", []), "name": n} for n, p in sorted(fc_config.PROVIDERS.items())]
    return PI_JS.replace("<json>", json.dumps(rows, sort_keys=True))

def pi_args(model) -> list[str]:
    """["-e", <path>] for a local model, after writing ~/.compose/pi-providers.js when its text changed; else []."""
    if fc_config.provider_of(model) is None:
        return []
    path = fc_config.CONFIG_PATH.parent / "pi-providers.js"
    text = pi_extension_text()
    if not path.exists() or path.read_text() != text:
        fc_core.atomic_write(path, text)
    return ["-e", str(path)]

def pi_env(model) -> dict:
    """{"COMPOSE_PI_MODEL": "<name>/<id>"} for a local model, else {}."""
    hit = fc_config.provider_of(model)
    if not hit:
        return {}
    env = fc_config.provider_env(hit[0])
    return {"COMPOSE_PI_MODEL": f"{hit[0]}/{hit[1]}", **({env: os.environ[env]} if env in os.environ else {})}

def cost(model, usage) -> float | None:
    """The turn's price: the PRICES price, else 0.0 for a local model, else usage["cost"]."""
    if model in fc_config.PRICES:
        return (usage["tokens_in"] * fc_config.PRICES[model][0] + usage["tokens_out"] * fc_config.PRICES[model][1]) / 1e6
    if fc_config.provider_of(model) is not None:
        return 0.0
    return usage.get("cost")

def reach(name) -> tuple[bool, str]:
    """Whether provider `name` answers a 5 s GET <base_url>/models (any HTTP answer counts), and why."""
    import urllib.error
    import urllib.request
    base_url = fc_config.PROVIDERS[name]["base_url"]
    try:
        env = fc_config.provider_env(name)
        key = os.environ.get(env)  # set but empty is no key: it would send a bare "Bearer "
        req = urllib.request.Request(base_url.rstrip("/") + "/models", headers={"Authorization": f"Bearer {key}"} if key else {})
        with urllib.request.urlopen(req, timeout=5) as r:
            return True, f"HTTP {r.status}"
    except urllib.error.HTTPError as e:
        e.close()
        return True, f"HTTP {e.code}"
    except OSError:  # URLError and socket timeouts are OSErrors
        return False, f"local provider {name} at {base_url} is not answering: start the server, then run again"

def doctor_rows() -> list[tuple]:
    """One doctor row per declared provider."""
    return [(f"local provider {n}", lambda checkout, n=n: (reach(n)[0], "not answering"), f"start the server at {p['base_url']}", "default", False, "manual")
            for n, p in sorted(fc_config.PROVIDERS.items())]

def opencode_provider(model) -> dict:
    """The OpenCode provider entry for a local model."""
    if model.startswith("pi:") or not (hit := fc_config.provider_of(model)):
        return {}
    name, mid = hit
    options = {"baseURL": fc_config.PROVIDERS[name]["base_url"]}
    if (env := fc_config.provider_env(name)) in os.environ:
        options["apiKey"] = f"{{file:{fc_config.key_file(os.environ[env], f'{name}.key')}}}"
    return {name: {"npm": "@ai-sdk/openai-compatible", "name": name, "options": options, "models": {mid: {"name": mid}}}}
