        cp_apply(self, {"providers": {"fakelocal": FAKE}})
        for m in ("pi:fakelocal/fake-1", "fakelocal/fake-1"): self.assertEqual(fc.fc_config.provider_of(m), ("fakelocal", "fake-1"))
